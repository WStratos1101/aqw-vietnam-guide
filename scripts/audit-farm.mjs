import fs from "node:fs";
import { validateFarmCatalog } from "../src/lib/farm-validation.mjs";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { validateMaterials } from "../src/lib/material-requirements.mjs";
const read = (p) => JSON.parse(fs.readFileSync(p, "utf8"));
const { items, regions } = read("src/content/farm/catalog.json"),
  manifest = read("src/content/farm/manifest.json");
assert.deepEqual(validateFarmCatalog({ items, regions }), []);
const source = read(manifest.source.path);
assert.equal(
  manifest.source.sha256,
  createHash("sha256")
    .update(fs.readFileSync(manifest.source.path))
    .digest("hex"),
  "Rebuild Farm after changing source export",
);
assert.equal(
  new Set(items.map((i) => i.id)).size,
  items.length,
  "Duplicate identity",
);
const allowed = (url) => {
  const u = new URL(url);
  assert.equal(u.protocol, "https:");
  assert.ok(
    ["aqwwiki.wikidot.com", "docs.google.com"].includes(u.hostname),
    url,
  );
};
for (const item of items) {
  assert.match(item.id, /^[a-z0-9]+(?:-[a-z0-9]+)*$/);
  assert.ok(
    item.officialName &&
      item.type &&
      item.acquisition.length &&
      item.sources.length,
  );
  assert.ok(["verified", "needs_review"].includes(item.verificationStatus));
  if (item.verificationStatus === "needs_review") assert.ok(item.reviewReason);
  if (item.regionId) {
    assert.ok(regions.some((r) => r.id === item.regionId));
    assert.ok(item.regionEvidence.length);
    assert.ok(
      !["nation", "legion", "chaos", "hollowborn"].includes(item.regionId),
    );
  } else assert.ok(item.reviewReason);
  item.sources.forEach(allowed);
  item.regionEvidence.forEach(allowed);
  for (const f of [
    item.location,
    item.availability,
    item.membership,
    item.price,
    item.joinCommand,
    item.requiredLevel,
    item.stability,
    ...item.boosts,
    ...item.prerequisites,
  ].filter(Boolean)) {
    allowed(f.source);
    assert.notEqual(f.value, undefined);
  }
  if (item.joinCommand)
    assert.match(item.joinCommand.value, /^\/join [a-z0-9]+$/);
  for (const route of item.acquisition) {
    allowed(route.source);
    assert.ok(route.method && route.description);
    if (route.materialTree)
      assert.deepEqual(validateMaterials(route.materialTree), []);
  }
  for (const index of item.communityEvidence.sourceIndices)
    assert.ok(source.nodes.some((n) => n.sourceIndex === index));
  for (const href of item.communityEvidence.guideHrefs)
    assert.ok(manifest.guideRecords.some((g) => g.href === href));
  if (item.image) {
    assert.equal(item.image.verificationStatus, "verified");
    assert.equal(item.image.usageStatus, "approved");
    assert.ok(item.image.credit && item.image.source);
    assert.ok(fs.existsSync("public" + item.image.path));
    assert.ok(!/misc\.png/.test(item.image.path));
  }
}
assert.equal(
  manifest.coverage.mappedItems,
  items.filter((i) => i.regionId).length,
);
assert.equal(
  manifest.coverage.unknownRegionItems,
  items.filter((i) => !i.regionId).length,
);
assert.equal(
  manifest.coverage.verifiedItemRecords,
  items.filter((i) => i.verificationStatus === "verified").length,
);
